let currentLang = localStorage.getItem('lang') || 'zh';

function t(key) {
    return (I18N[currentLang] && I18N[currentLang][key]) || (I18N.en[key]) || key;
}

function applyLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.getAttribute('data-i18n-title'));
    });
    const btn = document.getElementById('lang-toggle');
    if (btn) btn.textContent = currentLang === 'zh' ? 'EN' : '中文';
}

function toggleLanguage() {
    currentLang = currentLang === 'zh' ? 'en' : 'zh';
    localStorage.setItem('lang', currentLang);
    applyLanguage();
    if (investigationData) {
        renderSummary(investigationData);
        renderRiskAssessment(investigationData);
        renderTimeline(investigationData);
        renderConnectedAddresses(investigationData);
        renderWalletTokens(investigationData);
        renderSignalsSection(investigationData);
        renderInvestigationReport(investigationData);
    }
}

document.addEventListener('DOMContentLoaded', applyLanguage);
